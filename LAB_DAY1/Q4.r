data <- c(11, 13, 13, 15, 15, 16, 19, 20,20, 20, 21, 21, 22, 23, 24, 30,40, 45, 45, 45, 71, 72, 73, 75)
bins <- split(sort(data), cut(seq_along(data), 5, labels = FALSE))
mean_smooth <- unlist(lapply(bins, function(x) rep(mean(x), length(x))))
print(mean_smooth)
median_smooth <- unlist(lapply(bins, function(x) rep(median(x), length(x))))
print(median_smooth)
boundary_smooth <- unlist(lapply(bins, function(x) {
  b <- range(x)
  sapply(x, function(y) b[which.min(abs(b - y))])
}))
print(boundary_smooth)
